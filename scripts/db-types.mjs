// Generates TypeScript types for the local Supabase database into packages/shared/src/db.types.ts.
// Uses Node to write the file so the output is UTF-8 on every platform (PowerShell `>` writes UTF-16).
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const out = resolve(import.meta.dirname, "../packages/shared/src/db.types.ts");
const result = spawnSync(
  "supabase",
  ["gen", "types", "typescript", "--local", "--schema", "public"],
  {
    encoding: "utf8",
    shell: process.platform === "win32",
    maxBuffer: 32 * 1024 * 1024,
  },
);

if (result.status !== 0 || !result.stdout.trim()) {
  process.stderr.write(
    result.stderr || "supabase gen types produced no output. Is `supabase start` running?\n",
  );
  process.exit(result.status || 1);
}

const header = "// Generated by `pnpm db:types` (supabase gen types). Do not edit by hand.\n";
writeFileSync(out, header + result.stdout);
console.log(`Wrote ${out}`);
