// Copies contract ABIs from Foundry's out/ into packages/shared/src/abis as `as const` exports, and
// deployments/<chainId>.json files into packages/shared/src/addresses.ts.
//
// Run after `forge build` (and after a deploy to refresh addresses):
//   pnpm --filter @treecord/contracts export-abis
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const contractsDir = resolve(import.meta.dirname, "..");
const outDir = join(contractsDir, "out");
const deploymentsDir = join(contractsDir, "deployments");
const sharedSrc = resolve(contractsDir, "../shared/src");
const abisDir = join(sharedSrc, "abis");

const CONTRACTS = [
  "TreecordRoles",
  "CampaignFactory",
  "Campaign",
  "TreeRegistry",
  "VerificationGateway",
  "CarbonLedger",
] as const;

const HEADER = "// Generated by packages/contracts/script/export-abis.ts. Do not edit by hand.\n";

function camel(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1);
}

function exportAbis(): void {
  mkdirSync(abisDir, { recursive: true });
  const exports: string[] = [];
  for (const name of CONTRACTS) {
    const artifactPath = join(outDir, `${name}.sol`, `${name}.json`);
    if (!existsSync(artifactPath)) {
      throw new Error(`Missing ${artifactPath}. Run \`forge build\` first.`);
    }
    const { abi } = JSON.parse(readFileSync(artifactPath, "utf8")) as { abi: unknown[] };
    const constName = `${camel(name)}Abi`;
    writeFileSync(
      join(abisDir, `${camel(name)}.ts`),
      `${HEADER}export const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
    );
    exports.push(`export { ${constName} } from "./${camel(name)}.js";`);
  }
  writeFileSync(join(abisDir, "index.ts"), `${HEADER}${exports.join("\n")}\n`);
  console.log(`Exported ${CONTRACTS.length} ABIs to ${abisDir}`);
}

interface DeploymentFile {
  chainId: number;
  deployBlock: number;
  deployer: string;
  operator: string;
  attester: string;
  treasury: string;
  usdc: string;
  treecordRoles: string;
  treeRegistry: string;
  campaignImplementation: string;
  campaignFactory: string;
  verificationGateway: string;
  carbonLedger: string;
}

function exportAddresses(): void {
  const files = existsSync(deploymentsDir)
    ? readdirSync(deploymentsDir).filter((f) => /^\d+\.json$/.test(f))
    : [];

  const entries = files
    .map((file) => {
      const d = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8")) as DeploymentFile;
      const demoPath = join(deploymentsDir, `${d.chainId}-demo.json`);
      const demo = existsSync(demoPath)
        ? (JSON.parse(readFileSync(demoPath, "utf8")) as { campaign: string }).campaign
        : undefined;
      const lines = [
        `    chainId: ${d.chainId},`,
        `    deployBlock: ${d.deployBlock}n,`,
        `    deployer: "${d.deployer}",`,
        `    operator: "${d.operator}",`,
        `    attester: "${d.attester}",`,
        `    treasury: "${d.treasury}",`,
        `    usdc: "${d.usdc}",`,
        `    treecordRoles: "${d.treecordRoles}",`,
        `    treeRegistry: "${d.treeRegistry}",`,
        `    campaignImplementation: "${d.campaignImplementation}",`,
        `    campaignFactory: "${d.campaignFactory}",`,
        `    verificationGateway: "${d.verificationGateway}",`,
        `    carbonLedger: "${d.carbonLedger}",`,
      ];
      if (demo) lines.push(`    demoCampaign: "${demo}",`);
      return `  ${d.chainId}: {\n${lines.join("\n")}\n  },`;
    })
    .join("\n");

  const source = `${HEADER}import type { Address } from "viem";

/** Addresses of one Treecord deployment, written by packages/contracts/script/Deploy.s.sol. */
export interface TreecordDeployment {
  chainId: number;
  /** Block to start indexing from. */
  deployBlock: bigint;
  deployer: Address;
  operator: Address;
  attester: Address;
  treasury: Address;
  usdc: Address;
  treecordRoles: Address;
  treeRegistry: Address;
  campaignImplementation: Address;
  campaignFactory: Address;
  verificationGateway: Address;
  carbonLedger: Address;
  /** Campaign created by CreateDemoCampaign.s.sol, if any. */
  demoCampaign?: Address;
}

/** Known deployments by chain id. */
export const deployments: Partial<Record<number, TreecordDeployment>> = {
${entries}
};

/** The deployment for a chain. Throws if Treecord is not deployed there. */
export function getDeployment(chainId: number): TreecordDeployment {
  const deployment = deployments[chainId];
  if (!deployment) {
    throw new Error(\`No Treecord deployment for chain \${chainId}. Deploy and run export-abis.\`);
  }
  return deployment;
}
`;
  writeFileSync(join(sharedSrc, "addresses.ts"), source);
  console.log(`Exported ${files.length} deployment(s) to ${join(sharedSrc, "addresses.ts")}`);
}

exportAbis();
exportAddresses();
